# --- the exit codes of every command (requirement 22.8) ----------------------------------

# The command did what it was asked. Equal to :data:`~erp_mock.gateway.serve.EXIT_OK`, the
# code a serve process that was stopped on purpose returns.
EXIT_OK: Final = 0

# The command could not do it: a validation step reported errors (requirement 2.2), a
# Snapshot could not be built, or a port could not be bound
# (:data:`~erp_mock.gateway.serve.EXIT_BIND_FAILED`). The configuration or the machine is
# what has to change, not the command line.
EXIT_FAILED: Final = 1

# The command line or the environment is wrong: a missing ``--instance``, an option that
# does not exist, an option value that is not valid, a variable of requirement 23.9 that
# is not valid (requirement 23.10), or a profile or dataset the instance does not have
# (requirements 14.12 and 22.9). click answers every usage error with this code, so no
# command has to return it itself.
EXIT_USAGE: Final = 2


# --- the log of the service (design.md 7.3) ----------------------------------------------

# The logger every module of the package logs below, and the one :func:`setup_logging`
# configures: ``_LOG = logging.getLogger(__name__)`` of ``erp_mock.gateway.serve`` and the
# others are its children.
SERVICE_LOGGER: Final = "erp_mock"

# One line per record: the level, the module that logged it and the message. No timestamp:
# a deployer reads these lines next to the output of whatever started the process, which
# stamps them, and the times of the service that matter are in the trace (requirement 17.2).
LOG_FORMAT: Final = "%(levelname)s %(name)s: %(message)s"


def setup_logging(level: int = logging.INFO) -> None:
    """Point the log of the service at stderr and at nothing else (design.md 7.3).

    One handler on the ``erp_mock`` logger, writing to ``sys.stderr`` as it is at the
    moment of the call, and ``propagate`` turned off so that a handler of the root logger -
    which this package neither installs nor knows about - cannot be the one that writes a
    line of ours, possibly to stdout. Called once per command, by the group callback of
    :mod:`erp_mock.cli.main`, and calling it again replaces the handler rather than adding
    a second one.
    """
    logger = logging.getLogger(SERVICE_LOGGER)
    for installed in tuple(logger.handlers):
        logger.removeHandler(installed)
    handler = logging.StreamHandler(sys.stderr)
    handler.setFormatter(logging.Formatter(LOG_FORMAT))
    logger.addHandler(handler)
    logger.setLevel(level)
    logger.propagate = False


# --- the paths of a command (requirement 22.1) -------------------------------------------

# The defaults of requirement 22.1, kept as the text the requirement writes: the resolving
# happens where the option is parsed, so ``--help`` shows these two and not a path of the
# machine it was printed on.
DEFAULT_PACKS_DIR: Final = "./packs"
DEFAULT_DATA_DIR: Final = "./var"


def resolve_path(value: str | Path) -> Path:
    """``value`` as an absolute path, a relative one taken from the working directory.

    The resolving of requirement 22.1, which happens once, while the option is parsed:
    ``.`` and ``..`` are normalised away and the result is absolute, so what a command
    holds no longer depends on the working directory of the process. Symbolic links are
    *not* resolved - a path that leads through one is still the path the deployer wrote,
    which is what a message about it should name - and the path need not exist: a
    ``--instance`` directory that is not there is an error of validation step 1
    (requirement 2.12), reported with the rest of that step rather than as a usage error.
    """
    return Path(os.path.abspath(value))


class WorkingDirPath(click.ParamType):
    """A directory option whose value is resolved by :func:`resolve_path`.

    Nothing about the path is checked here: whether it exists, whether it is a directory
    and what is in it are questions of the validation steps, which report what they find as
    configuration errors (requirement 2.2) rather than as usage errors.
    """

    name = "directory"

    def convert(self, value: Any, param: click.Parameter | None, ctx: click.Context | None) -> Path:
        """``value`` - the text of the option or its default - as an absolute path."""
        return resolve_path(value if isinstance(value, Path) else str(value))


# The one instance of it; options of the later tasks take the same object.
DIRECTORY: Final = WorkingDirPath()


# --- the anchor date of a command (requirements 16.13 and 16.3) ---------------------------

# The shape of ``--anchor-date``, checked before the calendar is (design.md component 8):
# four digits, two and two, ASCII digits only, nothing around them. ``2026-2-3`` fails
# here, and so does a value with a space at either end.
ANCHOR_DATE_PATTERN: Final = re.compile(r"[0-9]{4}-[0-9]{2}-[0-9]{2}")

_ANCHOR_SHAPE: Final = "{value} 不是 YYYY-MM-DD 形式的日期（如 2026-10-09）"
_ANCHOR_CALENDAR: Final = "{value} 不是日历中存在的日期"


class AnchorDate(click.ParamType):
    """``--anchor-date``: a calendar date written YYYY-MM-DD (requirement 16.13).

    The shape first (:data:`ANCHOR_DATE_PATTERN`), the calendar second, so that each of
    the two mistakes is reported as itself; ``self.fail`` raises the usage error click
    answers with :data:`EXIT_USAGE`, a line on stderr naming the option and the value, and
    nothing on stdout. The year is 0001 to 9999 and February 30 does not exist, both of
    which ``date.fromisoformat`` settles (requirement 16.3).
    """

    name = "YYYY-MM-DD"

    def convert(self, value: Any, param: click.Parameter | None, ctx: click.Context | None) -> date:
        """``value`` as a :class:`datetime.date`, failing for anything else."""
        if isinstance(value, date):
            return value
        text = str(value)
        if ANCHOR_DATE_PATTERN.fullmatch(text) is None:
            self.fail(_ANCHOR_SHAPE.format(value=text), param, ctx)
        try:
            return date.fromisoformat(text)
        except ValueError:
            self.fail(_ANCHOR_CALENDAR.format(value=text), param, ctx)


# The one instance of it; the anchor date of serve comes from the clock configuration
# alone (requirement 16.1), so serve declares no such option.
ANCHOR_DATE: Final = AnchorDate()


