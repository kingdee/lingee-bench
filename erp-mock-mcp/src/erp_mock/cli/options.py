"""What the four commands share: their options, their environment and their output.

serve, stdio, validate and seed (requirement 22) are four different things that start the
same way. Each one names an instance configuration and a directory of business packs,
three of them may be given an anchor date, and all four write their log to stderr and
nothing else. That shared start is this module; :mod:`erp_mock.cli.main` is the group the
four commands hang off, and each command is a module of its own (tasks 24.2 to 24.4).

The options requirement 22 gives more than one command:

=================  =====================  ==========================  ======================
option             commands               default                     this module
=================  =====================  ==========================  ======================
``--instance``     all four, required     none, missing it is a       :data:`instance_option`
                                          usage error (req 22.8)
``--packs-dir``    all four               :data:`DEFAULT_PACKS_DIR`   :data:`packs_dir_option`
``--data-dir``     all four               :data:`DEFAULT_DATA_DIR`    :data:`data_dir_option`
``--anchor-date``  stdio, validate, seed  the ``clock`` of the        :data:`anchor_date_option`
                                          instance config (req 16.1)
=================  =====================  ==========================  ======================

``--host``, ``--port`` and ``--admin-port`` belong to serve alone, ``--profile`` to stdio
and ``--dataset`` to stdio and seed, so each of those is declared with its command.

A path option is already absolute when a command reads it: a relative path is resolved
against the working directory of the command (requirement 22.1, :func:`resolve_path`),
once, where the option is parsed. Nothing afterwards has to remember to do it, and nothing
afterwards depends on the working directory of the process. Symbolic links are left alone,
so the path that appears in a message is the path the deployer wrote, and the default is
kept as the text ``./packs`` rather than a resolved path, so ``--help`` shows what
requirement 22.1 says instead of a directory of the machine the help was printed on.

``--anchor-date`` is checked in two steps, both of them while click is still parsing the
options - that is, before anything is loaded, built or created (requirement 16.13):

===================================  ================================================
``2026-2-3``, ``2026/10/09``, ...    refused by :data:`ANCHOR_DATE_PATTERN`, the shape
``2026-02-30``, ``2100-02-29``, ...  refused by the calendar (``date.fromisoformat``)
===================================  ================================================

Two steps rather than one because the two are different mistakes and say so: a date of the
wrong shape is refused for its shape, and a date of the right shape that does not exist is
refused for not existing (design.md component 8, as :data:`~erp_mock.config.fields.DateText`
checks the same thing in the configuration). Either is a usage error, which click answers
with :data:`EXIT_USAGE` and a line on stderr naming the option and the value.

The environment, read once at startup and unchanged for as long as the process runs
(requirement 23.9, :func:`read_env`). A variable that is unset or empty is the default,
and the defaults are the constants of the parts that own the limits - this module repeats
no number of its own:

=================================  =============================  ==========================
variable                           default                        field of :class:`EnvValues`
=================================  =============================  ==========================
``ERP_MOCK_MAX_BODY_BYTES``        :data:`MAX_BODY_BYTES`         ``max_body_bytes``
``ERP_MOCK_MAX_SANDBOX_CALLS``     :data:`MAX_SANDBOX_CALLS`      ``resources.sandbox_calls``
``ERP_MOCK_MAX_DB_BYTES``          :data:`MAX_DB_BYTES`           ``resources.db_bytes``
``ERP_MOCK_MAX_CALLS_PER_SECOND``  :data:`MAX_CALLS_PER_SECOND`   ``resources.calls_per_second``
``ERP_MOCK_ALLOWED_ORIGINS``       no origin beyond the loopback  ``allowed_origins``
                                   origins of requirement 23.1
``ERP_MOCK_IDLE_SECONDS``          :data:`IDLE_SECONDS`           ``sandbox.idle_seconds``
``ERP_MOCK_FREEZE_SECONDS``        :data:`FREEZE_SECONDS`         ``sandbox.freeze_seconds``
``ERP_MOCK_RETENTION_SECONDS``     :data:`RETENTION_SECONDS`      ``sandbox.retention_seconds``
``ERP_MOCK_MAX_SANDBOXES``         :data:`MAX_SANDBOXES`          ``sandbox.max_sandboxes``
``ERP_MOCK_ADMIN_TOKEN``           generated by serve (req 23.5)  ``admin_token``, None here
``ERP_MOCK_MCP_TOKEN``             no token required (req 23.3)   ``mcp_token``
=================================  =============================  ==========================

The nine of requirement 23.9 are the first nine; the two tokens are read the same way and
at the same time (requirements 23.3 and 23.4) and have no form to check - a token is
whatever the deployer set, compared character for character later on. Every other value
has a form, and a value that does not have it is a usage error naming the variable and the
value (requirement 23.10): a number must be a positive decimal integer without a leading
zero, and an origin must be ``<scheme>://<host>[:<port>]`` with scheme http or https and
nothing else - no path, not even a trailing ``/``, no query, no fragment and no userinfo -
because requirement 23.1 compares it with an Origin header character for character, and
anything more than those three parts could never match one.

Why :class:`EnvValues` rather than the gateway's :class:`EnvSettings` straight away: the
Admin token is not settled yet. ``ERP_MOCK_ADMIN_TOKEN`` may be unset, in which case serve
generates a token and writes it to the token file (requirement 23.5, task 24.3), and
:class:`EnvSettings` refuses to exist without one. So the environment layer carries
``admin_token`` of None for "the environment named none", and serve settles it in one
line::

    env = read_env()                                        # exit code 2 for a bad value
    token = env.admin_token or write_token_file(data_dir)    # requirements 23.4 and 23.5
    settings = env.settings(token)                           # what the gateway is given

The log. :func:`setup_logging` puts one handler on the ``erp_mock`` logger, pointed at
stderr, and stops it from propagating to the root logger, whose handlers are nobody's
business here and could be pointed anywhere. stdout is left to the commands that have
something to say on it - the MCP messages of stdio (requirement 22.2) and the one line per
dataset of seed (requirement 22.10) - and ``print`` is not available anywhere in the
source (ruff rule T201), so a log line cannot reach stdout by accident.
"""

