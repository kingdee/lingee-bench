# A positive decimal integer without a leading zero (requirement 23.10). ASCII digits
# only: ``\d`` would also match the digits of other scripts, which ``int`` happily reads
# and no deployer means to write.
_POSITIVE_INT: Final = re.compile(r"[1-9][0-9]*")

_BAD_NUMBER: Final = "环境变量 {name} 的值 {value} 不是不带前导 0 的正整数"
_BAD_ORIGIN: Final = (
    "环境变量 {name} 的值 {value} 中的 {item} 不是协议为 http 或 https 的 <协议>://<主机>[:<端口>]"
)


@dataclass(frozen=True, slots=True)
class EnvValues:
    """What the environment of this process settled, less the Admin token (req 23.9).

    The fields are the fields of :class:`~erp_mock.gateway.serve.EnvSettings`, with one
    difference: ``admin_token`` is None where the environment named none, and
    :meth:`settings` is where serve puts the token it generated instead
    (requirements 23.4 and 23.5, task 24.3). :class:`EnvSettings` refuses to exist without
    an Admin token, which is why reading the environment cannot produce one directly.

    Built by :func:`read_env` and by nothing else; the defaults of the fields are the
    defaults of requirement 23.9, so ``EnvValues()`` is what an environment that sets none
    of the variables gives.
    """

    admin_token: str | None = None
    mcp_token: str | None = None
    allowed_origins: tuple[str, ...] = ()
    max_body_bytes: int = MAX_BODY_BYTES
    sandbox: SandboxLimits = DEFAULT_SANDBOX_LIMITS
    resources: ResourceLimits = DEFAULT_LIMITS

    def settings(self, admin_token: str) -> EnvSettings:
        """These values with ``admin_token`` as the Admin token, for the gateway.

        ``admin_token`` is :attr:`admin_token` where the environment set one
        (requirement 23.4) and the token serve generated and wrote to the token file
        where it did not (requirement 23.5); an empty one is refused by
        :class:`EnvSettings` itself, an Admin port without a token being a thing this
        service does not offer.
        """
        return EnvSettings(
            admin_token=admin_token,
            mcp_token=self.mcp_token,
            allowed_origins=self.allowed_origins,
            max_body_bytes=self.max_body_bytes,
            sandbox=self.sandbox,
            resources=self.resources,
        )


def read_env(environ: Mapping[str, str] | None = None) -> EnvValues:
    """Read the environment of a serve or stdio process once (requirements 23.9, 23.10).

    ``environ`` is the environment to read, ``os.environ`` by default. Read once, at
    startup, before anything is loaded: the values are what the process runs with for as
    long as it runs, and a value of the wrong form stops it before a port is bound or a
    sandbox is created.

    Raises :class:`click.UsageError` - :data:`EXIT_USAGE`, a line on stderr naming the
    variable and its value - for a number that is not a positive decimal integer without a
    leading zero and for an allowed origin that is not ``<scheme>://<host>[:<port>]``
    (requirement 23.10). The variables are read in the order of requirement 23.9, so an
    environment with more than one bad value always reports the same one.
    """
    env = os.environ if environ is None else environ
    max_body_bytes = _positive_int(env, MAX_BODY_BYTES_VAR)
    sandbox_calls = _positive_int(env, MAX_SANDBOX_CALLS_VAR)
    db_bytes = _positive_int(env, MAX_DB_BYTES_VAR)
    calls_per_second = _positive_int(env, MAX_CALLS_PER_SECOND_VAR)
    allowed_origins = _allowed_origins(env)
    idle_seconds = _positive_int(env, IDLE_SECONDS_VAR)
    freeze_seconds = _positive_int(env, FREEZE_SECONDS_VAR)
    retention_seconds = _positive_int(env, RETENTION_SECONDS_VAR)
    max_sandboxes = _positive_int(env, MAX_SANDBOXES_VAR)
    return EnvValues(
        admin_token=_text(env, ADMIN_TOKEN_VAR),
        mcp_token=_text(env, MCP_TOKEN_VAR),
        allowed_origins=allowed_origins,
        max_body_bytes=max_body_bytes,
        sandbox=SandboxLimits(
            idle_seconds=idle_seconds,
            freeze_seconds=freeze_seconds,
            retention_seconds=retention_seconds,
            max_sandboxes=max_sandboxes,
        ),
        resources=ResourceLimits(
            sandbox_calls=sandbox_calls,
            db_bytes=db_bytes,
            calls_per_second=calls_per_second,
        ),
    )


def _text(env: Mapping[str, str], name: str) -> str | None:
    """The value of ``name``, or None where it is unset or empty (requirement 23.9)."""
    value = env.get(name)
    return None if value is None or value == "" else value


def _positive_int(env: Mapping[str, str], name: str) -> int:
    """The number ``name`` is set to, or its default (requirements 23.9 and 23.10)."""
    text = _text(env, name)
    if text is None:
        return NUMERIC_DEFAULTS[name]
    if _POSITIVE_INT.fullmatch(text) is None:
        raise click.UsageError(_BAD_NUMBER.format(name=name, value=text))
    return int(text)


def _allowed_origins(env: Mapping[str, str]) -> tuple[str, ...]:
    """The origins of ``ERP_MOCK_ALLOWED_ORIGINS``, in the order they were written.

    The value is split on commas and nothing is stripped: requirement 23.1 compares each
    origin with an Origin header character for character, so an entry with a space around
    it is an entry that could never match one, and is refused rather than quietly mended.
    """
    text = _text(env, ALLOWED_ORIGINS_VAR)
    if text is None:
        return ()
    origins = tuple(text.split(","))
    for origin in origins:
        if not _is_origin(origin):
            raise click.UsageError(
                _BAD_ORIGIN.format(name=ALLOWED_ORIGINS_VAR, value=text, item=origin)
            )
    return origins


def _is_origin(text: str) -> bool:
    """Whether ``text`` is ``<scheme>://<host>[:<port>]`` with scheme http or https.

    The three parts and nothing else (requirement 23.10): no path - a trailing ``/``
    included - no query, no fragment, no userinfo, a port that is a number, and a host that
    is there. An Origin header carries exactly these three parts, and
    :class:`~erp_mock.gateway.middleware.OriginGuard` matches a configured origin against
    one literally, so anything else is configuration that could never allow a request.

    A space or a control character anywhere in the value refuses it before ``urlsplit``
    sees it: ``urlsplit`` strips those from both ends and removes tabs and newlines from
    the middle (the WHATWG rule), so ``" http://app.example"`` would otherwise be read as
    the origin it is not, and the entry the guard then held would match no Origin header.
    """
    if any(char <= " " for char in text):
        return False
    parts = urlsplit(text)
    if parts.scheme not in ORIGIN_SCHEMES:
        return False
    if parts.path or parts.query or parts.fragment:
        return False
    if parts.username is not None or parts.password is not None:
        return False
    try:
        # Reading .port is what refuses a port that is not a number.
        _ = parts.port
    except ValueError:
        return False
    return bool(parts.hostname)
