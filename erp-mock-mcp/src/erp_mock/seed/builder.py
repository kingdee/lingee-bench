"""The build of one initial dataset: its records, its Snapshot and the files beside it.

A dataset definition says what every sandbox of an instance starts out with. This module
turns one such definition, under one anchor date, into the three files of a Snapshot
(design.md component 6.1)::

    builder = SeedBuilder(loaded, instance_dir)
    ref = builder.build(dataset, date(2026, 10, 9), out_dir)    # raises SeedError
    ref.db, ref.meta, ref.aliases

Nothing is written into the tables directly. The build starts from an empty database whose
counters are all 0 and replays the definition through the engine, one operation at a time,
so the stock transactions, the writebacks, the automatic close of a source bill, the
numbers and the amounts of the Snapshot are the ones the same calls would have produced in
a sandbox (requirement 20.17, seed-data.md section 2). The order, which is what fixes every
internal id and every generated code:

1. the Shared_Data of each pack of ``include_shared``, in the written order of that list,
   within a pack by the code points of the file path below ``seed/shared/`` and within a
   file in the written order of ``records`` (requirement 20.17);
2. the records of ``entities``, in written order, each one finished before the next one
   begins: the record is created - or generated by a push where it declares a ``source`` -
   with its own field values, and then the state operations of its ``status`` run, a
   ``closed`` standard bill ending in a close that counts as a manual one
   (requirement 20.2);
3. the records of ``bulk``, item by item and ``count`` records per item, every field a pack
   binds a generator to drawn and every other field left to its default (req 20.4).

The business context of every one of those operations is the anchor date and the current
user of the dataset (requirement 20.5): date expressions, ``context.today`` and a
``default_context: today`` take the anchor date, and ``context.user`` and a
``default_context: user`` take the ``current_user`` of the dataset, or of instance.yaml
where the dataset declares none. That user is a record of the build itself, so until the
operation that creates it has run there is no such record and the context user is empty;
loading step 8 is what checks that the user exists at all (requirement 2.10).

What the build decides and the static pass could not (:mod:`erp_mock.seed.resolve`): the
internal id an alias stands for, the record a code names among those created so far, the
value a generator draws, the date an expression gives at the anchor date, and the Python
type each written value reaches the engine as - a decimal as a Decimal of the field's
precision and a date as a ``datetime.date``, the way the tools layer hands over an argument
(design.md 5.2).

Where a build fails, always with :class:`~erp_mock.seed.resolve.SeedError` naming the file,
the configuration path and the reason:

- the static pass over the definition, before anything is created (requirement 20.6);
- a code that names no created record of its entity or more than one, and a value that does
  not fit the type of its field (requirement 20.6);
- :data:`~erp_mock.seed.generators.DISCARD_LIMIT` drawn values discarded in a row for one
  field (requirement 20.7);
- any engine operation that returns an error, at that operation: the reason names the
  operation, the error code and the rule id (requirement 20.15);
- INV-1, INV-2, INV-3 or INV-6 not holding once every record is there, the reason naming
  the invariants and the records they are about (requirement 20.9).

Only the Shared_Data, the generators of the packs and the dataset definition are read, so
the example data of ``seed/examples/`` has no part in a Snapshot and changing it leaves the
three files byte for byte as they were (requirement 20.8). The bytes of the Snapshot itself
come from ``VACUUM INTO`` over the build database, run once the records are there and the
invariants hold (:func:`~erp_mock.state.snapshot.finalize_snapshot`); the metadata and the
alias map are JSON with a fixed key order and carry no build time (requirements 20.10
and 20.13).

What is not here: the cache below the data directory that keys these files by (dataset,
anchor date) and replaces them atomically, which is :mod:`erp_mock.seed.cache`
(requirements 20.11 and 20.12).
"""

