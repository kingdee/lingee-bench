@dataclass(frozen=True, slots=True)
class _Place:
    """Where an error of a build is: the configuration file and the item inside it.

    The dataset definition for everything of ``entities`` and ``bulk``, and
    ``<pack>/seed/shared/<file>`` for a record a business pack provides.
    """

    file: str
    path: str

    def at(self, key: str) -> "_Place":
        """The place of the key ``key`` below this one."""
        return _Place(self.file, f"{self.path}.{key}")

    def item(self, index: int) -> "_Place":
        """The place of the item ``index`` of this one."""
        return _Place(self.file, f"{self.path}[{index}]")

    def error(self, reason: str) -> SeedError:
        """A :class:`~erp_mock.seed.resolve.SeedError` about this place."""
        return SeedError(self.file, self.path, reason)


class _Build:
    """One run of a build: the database being filled and what has been created so far.

    ``_aliases`` holds the internal id of every record of ``entities`` created so far,
    which is what an alias reference resolves to and what the alias map of the Snapshot is
    written from; ``_codes`` holds the ids of the created records of each (entity, code),
    which is what a reference written as a code resolves to - the code has to name exactly
    one of them (requirement 20.16). ``_user`` says whether the record of the current user
    is already there, since the business context has no user before it is
    (requirement 20.5).
    """

    __slots__ = (
        "_aliases",
        "_anchor",
        "_codes",
        "_domain",
        "_engine",
        "_generators",
        "_packs",
        "_plan",
        "_store",
        "_user",
    )

    def __init__(
        self,
        engine: Engine,
        store: SandboxStore,
        plan: SeedPlan,
        anchor: date,
        packs: Sequence[RawPack] = (),
    ) -> None:
        self._engine = engine
        self._domain = engine.domain
        self._store = store
        self._plan = plan
        self._anchor = anchor
        self._packs = {pack.name: pack for pack in packs}
        # The one pseudo random sequence of the build, created before the first draw
        # (requirement 20.3).
        self._generators = ValueGenerators(plan.random_seed)
        self._aliases: dict[str, str] = {}
        self._codes: dict[tuple[str, str], list[str]] = {}
        self._user = False

    # --- the three groups of records (requirement 20.17) ---------------------------------

    def run(self) -> FrozenMap[str, str]:
        """Create the Shared_Data, the records of ``entities`` and those of ``bulk``.

        In that order, and the invariants are checked once all of them are there
        (requirement 20.9). Returns the internal id of each alias, which becomes the alias
        map of the Snapshot (requirement 20.10).
        """
        self._shared_data()
        self._entities()
        self._bulk()
        self._invariants()
        return FrozenMap(self._aliases)

    def _shared_data(self) -> None:
        """The Shared_Data of the packs of ``include_shared`` (requirement 20.17).

        The packs in the written order of the list, the files of a pack by the code points
        of their path - which is the order they were read in
        (:func:`~erp_mock.loader.yaml_io.list_files`) - and the records of a file in written
        order. A name of ``include_shared`` that is no pack of the instance was reported by
        loading step 5 (requirement 2.10), so it is passed over here rather than reported
        again.
        """
        for name in self._plan.include_shared:
            pack = self._packs.get(name)
            if pack is None:
                continue
            for document in pack.shared_data:
                place = _Place(f"{pack.name}/{document.file}", _RECORDS_KEY)
                for index, record in enumerate(document.document.records):
                    self._shared_record(place.item(index), record)

    def _shared_record(self, place: _Place, record: Mapping[str, ScalarDefault]) -> None:
        """Create one record of a ``seed/shared/`` file (requirement 20.17).

        The record names its entity under the reserved key ``kind`` and writes its field
        values the way a dataset record writes them, a reference as the code of the record
        it names (requirement 20.16); it has no alias, no generator and no status, so it is
        one create and nothing else.
        """
        entity = self._shared_entity(place, record.get(KIND_KEY))
        fields = tuple(self._shared_fields(place, entity, record))
        self._create(place, entity.name, self._values(place, entity.name, fields))

    def _entities(self) -> None:
        """The records of ``entities``, in written order (requirements 20.2 and 20.17).

        One record at a time, all of its operations before the next one begins: the create
        or the push that generates it, and then the state operations its ``status`` amounts
        to, which the static pass worked out
        (:func:`~erp_mock.seed.resolve.status_actions`). The internal id goes into the alias
        map as soon as the record is there, so a later record may reference it.
        """
        for record in self._plan.records:
            place = _Place(self._plan.file, record.config_path)
            record_id = self._record(place, record)
            self._aliases[record.alias] = record_id
            for action in record.actions:
                self._run(place, action, TransitionOp(record.kind, record_id, action))

    def _record(self, place: _Place, record: PlanRecord) -> str:
        """Create or push one record of ``entities`` and return its id (requirement 20.2).

        The header fields are written in this one operation, whether the record is created
        or generated by a push, so the number of a pushed bill is allocated from its own
        business date (:class:`~erp_mock.domain.engine.PushOp`).
        """
        values = self._values(place, record.kind, record.fields)
        lines = self._lines(place, record)
        if record.source is None or record.conversion is None:
            return self._create(place, record.kind, values, lines)
        op = PushOp(
            conversion=record.conversion,
            source_id=self._aliases[record.source],
            lines=() if lines is None else lines,
            values=values,
        )
        return _record_id(self._run(place, _PUSH, op))

    def _lines(self, place: _Place, record: PlanRecord) -> Lines | None:
        """The lines of one record of ``entities``, None for a record that has none.

        A pushed line names the source line it comes from by its line number, which is the
        internal id of the line of that number of the source bill
        (:func:`~erp_mock.domain.numbering.line_id`, requirement 20.16).
        """
        if not record.lines:
            return None
        source_id = None if record.source is None else self._aliases[record.source]
        lines: list[Arguments] = []
        for line in record.lines:
            at = _Place(place.file, line.config_path)
            values = dict(self._values(at, record.kind, line.fields))
            if source_id is not None and line.source_line is not None:
                values[SOURCE_LINE_ID] = line_id(source_id, line.source_line)
            lines.append(FrozenMap(values))
        return tuple(lines)

    def _bulk(self) -> None:
        """The records of ``bulk``, item by item and ``count`` per item (req 20.4).

        Every field a business pack binds a generator to takes a drawn value, in the order
        the bindings are written, and every other field of the record takes its default;
        the records get no alias.
        """
        for item in self._plan.bulk:
            place = _Place(self._plan.file, item.config_path)
            for _ in range(item.count):
                self._create(place, item.kind, self._values(place, item.kind, item.fields))

    def _invariants(self) -> None:
        """Check INV-1, INV-2, INV-3 and INV-6 over the records of the build (req 20.9).

        One read of the finished database; the error names every invariant that does not
        hold, the records it is about and the two values, in the order
        :func:`~erp_mock.domain.invariants.check_invariants` reports them.
        """
        with self._store.transaction() as uow:
            violations = check_invariants(uow, self._domain)
        if not violations:
            return
        broken = "；".join(violation.text for violation in violations)
        raise SeedError(self._plan.file, None, _INVARIANTS_BROKEN.format(violations=broken))

    # --- one operation -------------------------------------------------------------------

    def _create(
        self, place: _Place, target: str, values: Arguments, lines: Lines | None = None
    ) -> str:
        """Create one record of ``target`` and return its internal id (requirement 5.1)."""
        return _record_id(self._run(place, _CREATE, CreateOp(target, values, lines)))

    def _run(self, place: _Place, operation: str, op: Operation) -> RecordView:
        """Run ``op`` against the build database and return the record it wrote.

        The build stops at the first operation the engine answers with an error, and the
        reason names the operation, the error code and the rule id that decided it
        (requirement 20.15). A record a create or a push wrote is noted as created, so a
        later reference finds it by its code and the business context gains its user once
        that record is there (requirements 20.5 and 20.16).
        """
        try:
            result = self._engine.run(self._store, self._context(), op)
        except ErpError as error:
            raise place.error(_engine_reason(operation, error)) from error
        view = result.view
        if not isinstance(view, RecordView):
            raise RuntimeError(f"{operation} 没有返回记录：{type(view).__name__}")
        self._note(op, view)
        return view

    def _context(self) -> OperationContext:
        """The business context of the next operation (requirement 20.5).

        The anchor date and the current user of the dataset; the user is empty until the
        record it names has been created, since there is no such record before that
        (design.md 6.1). No trace sequence number: a build is no tools/call, so the
        effective calls of the Snapshot stay empty (requirement 18.10).
        """
        return OperationContext(
            anchor_date=self._anchor,
            current_user_id=self._plan.current_user if self._user else None,
        )

    def _note(self, op: Operation, view: RecordView) -> None:
        """Note the record ``view`` as created: its code, and whether it is the user.

        The code is read from the record itself rather than from what was written, so a
        code the engine generated is one a later reference can name (requirement 20.16).
        """
        if not isinstance(op, CreateOp | PushOp):
            return
        record_id = _record_id(view)
        code = view.fields.get(_CODE)
        if isinstance(op, CreateOp) and isinstance(code, str) and code:
            self._codes.setdefault((op.target, code), []).append(record_id)
        if record_id == self._plan.current_user:
            self._user = True

    # --- the written values of one level -------------------------------------------------

    def _values(self, place: _Place, kind: str, fields: Sequence[PlanField]) -> Arguments:
        """The arguments of one record, header or line, in written order.

        Each value is resolved and typed the way the engine takes it (:meth:`_value`). A
        ``name`` the record is given counts as taken, so no value drawn later repeats it,
        and it is what a ``short_name`` generator of the same record derives from
        (requirement 20.7).
        """
        values: dict[str, Value] = {}
        name: str | None = None
        for item in fields:
            value = self._value(place.at(item.written), kind, item.field, item.value, name)
            values[item.name] = value
            if item.name == NAME_FIELD and isinstance(value, str):
                name = value
                self._generators.add_name(kind, value)
        return FrozenMap(values)

    def _value(
        self, place: _Place, kind: str, field: FieldModel, value: PlanValue, name: str | None
    ) -> Value:
        """One written value as the engine takes it (requirements 20.3, 20.5 and 20.16).

        An alias gives the internal id of the record it names, a code the id of the one
        created record of that entity, a date expression its value at the anchor date and a
        generator a value drawn from the build's random sequence; everything else is the
        value the definition writes, typed by its field (:meth:`_typed`).
        """
        match value:
            case AliasId(alias=alias):
                return self._aliases[alias]
            case CodeId(entity=entity, code=code):
                return self._code_id(place, entity, code)
            case DateAt(expr=expr):
                return self._date(place, expr)
            case Drawn(decl=decl):
                return self._typed(place, field, self._draw(place, kind, field, decl, name))
            case Written(value=written):
                return self._typed(place, field, written)
            case _:
                assert_never(value)

    def _typed(self, place: _Place, field: FieldModel, value: GeneratedValue) -> Value:
        """``value`` as the Python type its field is stored as (requirements 4.7 and 12.6).

        A decimal field takes a Decimal of its own precision, which a written text, a whole
        number and a drawn Decimal all become; an int field an int, a bool field a bool, and
        every other field the text itself. A value of another type cannot be stored, which
        the engine would answer with a TypeError rather than with a business error, so it is
        reported here as the mistake in the definition that it is.
        """
        places = _DECIMAL_PLACES.get(field.type)
        if places is not None:
            return self._decimal(place, field, places, value)
        if field.type == _INT_TYPE:
            if isinstance(value, bool) or not isinstance(value, int):
                raise place.error(_value_type(field, value))
            return value
        if field.type == _BOOL_TYPE:
            if not isinstance(value, bool):
                raise place.error(_value_type(field, value))
            return value
        if not isinstance(value, str):
            raise place.error(_value_type(field, value))
        return value

    def _decimal(
        self, place: _Place, field: FieldModel, places: int, value: GeneratedValue
    ) -> Decimal:
        """``value`` as a Decimal of ``places`` decimal places (requirements 4.7, 12.6)."""
        if isinstance(value, bool):
            raise place.error(_value_type(field, value))
        try:
            number = value if isinstance(value, Decimal) else to_decimal(value)
            return round_half_up(number, places)
        except (ValueError, ArithmeticError) as error:
            reason = _VALUE_DECIMAL.format(type=field.type, field=field.name, value=value)
            raise place.error(reason) from error

    def _code_id(self, place: _Place, entity: str, code: str) -> str:
        """The id of the created record of ``entity`` whose code is ``code`` (req 20.16).

        Among the records created so far, and there has to be exactly one of them
        (requirement 20.6); the code of a record the build creates later is not one the
        reference can name. More than one is what the uniqueness check of the engine keeps
        from happening in the first place (requirement 5.8), so that reason is a guard
        rather than something a dataset reaches.
        """
        found = self._codes.get((entity, code), [])
        if not found:
            raise place.error(_NO_CODE.format(entity=entity, code=code))
        if len(found) > 1:
            reason = _MANY_CODES.format(
                entity=entity, count=len(found), code=code, ids="、".join(found)
            )
            raise place.error(reason)
        return found[0]

    def _date(self, place: _Place, expr: _DateTree) -> date:
        """The value of the date expression ``expr`` at the anchor date (16.5, 20.5)."""
        try:
            return eval_date_expr(expr, self._anchor)
        except DateExprRangeError as error:
            reason = _DATE_RANGE.format(expr=print_date_expr(expr), anchor=self._anchor)
            raise place.error(reason) from error

    def _draw(
        self,
        place: _Place,
        kind: str,
        field: FieldModel,
        decl: GeneratorObject,
        name: str | None,
    ) -> GeneratedValue:
        """One value from the build's random sequence (requirements 20.3 and 20.7).

        The static pass checked the parameters of the generator against the field, so what
        is left to go wrong here is the discard limit: the drawn value kept containing a
        blacklisted word or repeating a name of the same entity (requirement 20.7).
        """
        try:
            return self._generators.value(decl, entity=kind, field=field.name, name=name)
        except DiscardLimitExceeded as error:
            raise place.error(str(error)) from error

    # --- one record of a pack's Shared_Data (requirement 20.17) --------------------------

    def _shared_entity(self, place: _Place, kind: ScalarDefault | None) -> EntityModel:
        """The entity a Shared_Data record declares under ``kind``.

        The document model has checked that the key is there and is a name
        (:class:`~erp_mock.config.pack.SharedDataFile`), so what is left is whether the
        instance has such an entity.
        """
        entity = self._domain.entities.get(kind) if isinstance(kind, str) else None
        if entity is None:
            raise place.at(KIND_KEY).error(_UNKNOWN_SHARED_KIND.format(kind=kind))
        return entity

    def _shared_fields(
        self, place: _Place, entity: EntityModel, record: Mapping[str, ScalarDefault]
    ) -> Iterator[PlanField]:
        """The written values of a Shared_Data record, resolved like a dataset record.

        The key names its field the way a dataset writes it - a reference without the
        ``_id`` suffix and a field named ``kind`` as ``<kind value>_kind`` - and the field
        has to be writable; a reference value is the code of the record it names and a date
        value an expression relative to the anchor date (requirements 20.6 and 20.16).
        """
        for key, written in record.items():
            if key == KIND_KEY:
                continue
            at = place.at(key)
            field = self._shared_field(entity, key)
            if field is None:
                raise at.error(_UNKNOWN_FIELD.format(kind=entity.name, field=key))
            if not field.writable:
                raise at.error(_READONLY_FIELD.format(field=field.name))
            yield PlanField(field, key, self._shared_value(at, field, written))

    def _shared_field(self, entity: EntityModel, key: str) -> FieldModel | None:
        """The field of ``entity`` the key ``key`` of a Shared_Data record names (20.16)."""
        field = lookup_field(entity.fields, key)
        if field is None and key == f"{entity.name}{KIND_SUFFIX}":
            return lookup_field(entity.fields, KIND_KEY)
        return field

    def _shared_value(self, place: _Place, field: FieldModel, written: ScalarDefault) -> PlanValue:
        """One written value of a Shared_Data record, by the type of its field (20.16)."""
        if field.type == REF_TYPE and field.ref is not None:
            if not isinstance(written, str):
                raise place.error(_value_type(field, written))
            return CodeId(entity=field.ref, code=written)
        if field.type == DATE_TYPE:
            return DateAt(self._shared_date(place, field, written))
        return Written(written)

    def _shared_date(self, place: _Place, field: FieldModel, written: ScalarDefault) -> _DateTree:
        """A date value of a Shared_Data record as a parsed expression (requirement 20.6).

        Written relative to the anchor date, as a dataset writes a date, so a date of the
        calendar is none of them (seed-data.md section 4); ``month(N)`` is a period and no
        value of a date field either.
        """
        expr = None
        if isinstance(written, str):
            try:
                expr = parse_date_expr(written, Category.DATE)
            except DateExprError:
                expr = None
        if expr is None or isinstance(expr, MonthPeriod):
            raise place.error(_NOT_DATE.format(field=field.name, value=written))
        return expr


# --- the two JSON files (requirement 20.10) ----------------------------------------------


def _aliases_json(key: SnapshotKey, aliases: Mapping[str, str]) -> dict[str, JsonValue]:
    """The object ``aliases.json`` holds: the dataset, then the aliases (req 20.10).

    The keys of ``aliases`` are sorted by Unicode code point, so the file does not depend
    on the order the records were created in (requirement 19.10).
    """
    return {
        "dataset": key.dataset,
        "aliases": {alias: aliases[alias] for alias in sorted(aliases)},
    }


def _write_json(path: Path, payload: Mapping[str, JsonValue]) -> None:
    """Write ``payload`` to ``path`` as indented JSON and flush it to disk.

    The cache replaces an entry only once its three files are on disk (design.md 6.2); the
    Snapshot itself is flushed by :func:`~erp_mock.state.snapshot.finalize_snapshot`.
    """
    path.write_bytes(encode_utf8(dumps_pretty(payload)))
    fd = os.open(path, os.O_RDONLY)
    try:
        os.fsync(fd)
    finally:
        os.close(fd)


# --- reasons and small readings ----------------------------------------------------------


def _closed_before(plan: SeedPlan, anchor: date) -> str:
    """``periods.closed_before`` of ``plan`` at ``anchor``: the ``YYYY-MM`` of a month."""
    try:
        return eval_date_expr(plan.closed_before, anchor)
    except DateExprRangeError as error:
        reason = _DATE_RANGE.format(expr=print_date_expr(plan.closed_before), anchor=anchor)
        raise SeedError(plan.file, PERIODS_PATH, reason) from error


def _engine_reason(operation: str, error: ErpError) -> str:
    """Why ``operation`` failed: its name, the error code and the rule id (req 20.15)."""
    if error.rule_id is None:
        return _ENGINE_ERROR.format(operation=operation, code=error.code, message=error.message)
    return _ENGINE_ERROR_RULE.format(
        operation=operation, code=error.code, rule=error.rule_id, message=error.message
    )


def _value_type(field: FieldModel, value: object) -> str:
    """Why ``value`` cannot fill ``field``: it is not of the type the field stores."""
    return _VALUE_TYPE.format(type=field.type, field=field.name, value=value)


def _record_id(view: RecordView) -> str:
    """The internal id of the record ``view`` returns (requirement 4.1)."""
    record_id = view.fields.get(ID_COLUMN)
    if not isinstance(record_id, str):
        raise RuntimeError(f"写操作的结果没有内部 ID：{record_id!r}")
    return record_id
