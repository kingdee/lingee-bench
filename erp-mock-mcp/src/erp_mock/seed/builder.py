# --- what one build produces (design.md component 6) -------------------------------------


@dataclass(frozen=True, slots=True)
class SnapshotKey:
    """What a Snapshot is of: one dataset at one anchor date (requirement 20.11).

    ``dataset`` is ``<name>@<version>`` and ``anchor`` the anchor date the dataset was
    built under; the cache keeps one directory per key (design.md 6.2).
    """

    dataset: str
    anchor: date


@dataclass(frozen=True, slots=True)
class SnapshotRef:
    """The three files of one Snapshot and the key they belong to (requirement 20.10).

    ``db`` is the Snapshot itself, which a sandbox is copied from, ``meta`` its metadata
    and ``aliases`` the map of the dataset's aliases to internal ids.
    """

    db: Path
    meta: Path
    aliases: Path
    key: SnapshotKey

    @property
    def files(self) -> tuple[Path, Path, Path]:
        """The three files, in the order ``db``, ``meta``, ``aliases``."""
        return (self.db, self.meta, self.aliases)

    @property
    def directory(self) -> Path:
        """The directory the three files are in."""
        return self.db.parent


@dataclass(frozen=True, slots=True)
class SnapshotMeta:
    """The metadata of one Snapshot, as ``meta.json`` holds it (requirement 20.10).

    The fields are the keys of that file, in the order it writes them, and none of them is
    about the build itself: the file carries no build time, so two builds of one key write
    the same bytes (requirements 20.10 and 20.13).

    - ``dataset`` and ``version``: what the definition calls itself;
    - ``random_seed``: the seed of the one random sequence of the build;
    - ``anchor_date``: the date the dataset was built under;
    - ``closed_before``: ``periods.closed_before`` evaluated at that date, the ``YYYY-MM``
      of the first open period;
    - ``current_user``: the current user of the build context, None where neither the
      dataset nor instance.yaml names one;
    - ``framework_version`` and ``meta_model_version``: the engine's own versions;
    - ``packs``: the version each business pack is pinned to, in the order instance.yaml
      references them;
    - ``dataset_sha256``: the SHA-256 of the bytes of the dataset definition file.

    The last six are what a cached Snapshot is checked against (requirement 20.12).
    """

    dataset: str
    version: str
    random_seed: int
    anchor_date: date
    closed_before: str
    current_user: str | None = None
    framework_version: str = FRAMEWORK_VERSION
    meta_model_version: str = META_MODEL_VERSION
    packs: FrozenMap[str, str] = FrozenMap()
    dataset_sha256: str = ""

    @property
    def key(self) -> SnapshotKey:
        """The key of the Snapshot this metadata belongs to."""
        return SnapshotKey(dataset=f"{self.dataset}@{self.version}", anchor=self.anchor_date)

    def as_json(self) -> dict[str, JsonValue]:
        """The object ``meta.json`` holds, its keys in the order of this class."""
        return {
            "dataset": self.dataset,
            "version": self.version,
            "random_seed": self.random_seed,
            "anchor_date": self.anchor_date.isoformat(),
            "closed_before": self.closed_before,
            "current_user": self.current_user,
            "framework_version": self.framework_version,
            "meta_model_version": self.meta_model_version,
            "packs": dict(self.packs),
            "dataset_sha256": self.dataset_sha256,
        }


def snapshot_key(dataset: DatasetDef, anchor: date) -> SnapshotKey:
    """The key of the Snapshot of ``dataset`` at ``anchor`` (requirement 20.11)."""
    return SnapshotKey(dataset=f"{dataset.dataset}@{dataset.version}", anchor=anchor)


def snapshot_ref(directory: Path, key: SnapshotKey) -> SnapshotRef:
    """The three files of ``key`` below ``directory``, whether they are there or not.

    What :meth:`SeedBuilder.build` writes, and what the cache looks for when it decides
    whether an entry can be taken up (requirement 20.12).
    """
    return SnapshotRef(
        db=directory / SNAPSHOT_FILENAME,
        meta=directory / META_FILENAME,
        aliases=directory / ALIASES_FILENAME,
        key=key,
    )


# --- the builder (design.md component 6.1) -----------------------------------------------


class SeedBuilder:
    """Builds the Snapshots of the initial datasets of one loaded instance configuration.

    One instance per loaded configuration, shared by every dataset and every anchor date:
    the builder holds nothing of a build, which lives on the state of that build, and reads
    the business configuration from ``loaded`` alone (requirement 1.10).

    ``instance_dir`` is the instance directory the dataset definitions were read from,
    which the SHA-256 of a definition file is taken over (requirement 20.12). ``engine`` is
    the engine of the same configuration, which the loader builds with the expression trees
    it parsed at step 5; None builds one from the domain model, which parses the same trees
    again (:class:`~erp_mock.domain.engine.Engine`).
    """

    __slots__ = ("_engine", "_instance_dir", "_loaded", "_schema")

    def __init__(
        self, loaded: LoadedInstance, instance_dir: Path, engine: Engine | None = None
    ) -> None:
        self._loaded = loaded
        self._instance_dir = instance_dir
        self._engine = engine if engine is not None else Engine(loaded.domain)
        self._schema = build_schema(loaded.domain)

    @property
    def loaded(self) -> LoadedInstance:
        """The read-only configuration of the instance the builder serves (design.md 2.4)."""
        return self._loaded

    @property
    def domain(self) -> DomainModel:
        """The resolved configuration every operation of a build runs against."""
        return self._loaded.domain

    @property
    def engine(self) -> Engine:
        """The engine the records of a build are created through (design.md 4.1)."""
        return self._engine

    @property
    def schema(self) -> StorageSchema:
        """The tables of the instance, which every Snapshot of it holds (design.md 3.1)."""
        return self._schema

    @property
    def versions(self) -> VersionInfo:
        """The versions the metadata of a Snapshot carries (requirement 20.10)."""
        return self._loaded.versions

    def build(
        self, dataset: DatasetDef, anchor: date, out_dir: Path, *, file: str | None = None
    ) -> SnapshotRef:
        """Build the Snapshot of ``dataset`` at ``anchor`` into ``out_dir``.

        ``file`` is the definition file of ``dataset``, relative to the instance directory,
        as an error names it and as the digest of the metadata is taken over; None derives
        ``datasets/<name>.yaml`` from the definition
        (:func:`~erp_mock.seed.resolve.dataset_file`). ``out_dir`` is created when it is not
        there and must hold none of the files of a build yet, which is what the temporary
        directory of the cache gives (design.md 6.2): the build database is written there
        too and is removed once the Snapshot is out of it, so a build that failed leaves it
        behind - with the records it had created in it - and the cache throws the whole
        directory away (requirement 20.11).

        Returns the three files it wrote, all of them on disk. Raises
        :class:`~erp_mock.seed.resolve.SeedError` for everything that can be wrong with the
        dataset, with the Shared_Data or with the data they produce (module docstring).
        """
        plan = self.plan(dataset, file=file)
        meta = self._meta(plan, anchor)
        ref = snapshot_ref(out_dir, meta.key)
        out_dir.mkdir(parents=True, exist_ok=True)
        build_db = out_dir / BUILD_DB_FILENAME
        aliases = self._records(plan, anchor, build_db)
        finalize_snapshot(build_db, ref.db)
        build_db.unlink()
        _write_json(ref.meta, meta.as_json())
        _write_json(ref.aliases, _aliases_json(meta.key, aliases))
        return ref

    def plan(self, dataset: DatasetDef, *, file: str | None = None) -> SeedPlan:
        """The static pass over ``dataset`` against this instance's configuration.

        What :meth:`build` walks (:func:`~erp_mock.seed.resolve.resolve`); ``file`` is the
        definition file, as :meth:`build` takes it. Raises
        :class:`~erp_mock.seed.resolve.SeedError` for everything the definition and the
        configuration settle between them (requirement 20.6).
        """
        return resolve(
            dataset,
            self.domain,
            self._loaded.packs,
            file=file,
            instance_user=self._loaded.instance.current_user,
        )

    def metadata(
        self, dataset: DatasetDef, anchor: date, *, file: str | None = None
    ) -> SnapshotMeta:
        """The metadata the Snapshot of ``dataset`` at ``anchor`` would carry (req 20.10).

        What :meth:`build` writes as ``meta.json``, worked out without building anything:
        the Snapshot cache decides whether an entry can be taken up by comparing the
        metadata beside it against this (:mod:`erp_mock.seed.cache`, requirement 20.12).
        Arguments as in :meth:`build`; raises :class:`~erp_mock.seed.resolve.SeedError` for
        what the static pass reports and for a definition file that cannot be read, whose
        SHA-256 the metadata carries.
        """
        return self._meta(self.plan(dataset, file=file), anchor)

    def _records(self, plan: SeedPlan, anchor: date, build_db: Path) -> FrozenMap[str, str]:
        """Create every record of ``plan`` in a new build database at ``build_db``.

        The database starts out empty with every counter at 0 (requirement 20.17) and is
        closed again whether the build got through or not, so the file ``VACUUM INTO`` reads
        afterwards is complete and a failed build leaves nothing open.
        """
        store = build_snapshot_db(build_db, self._schema)
        try:
            return _Build(self._engine, store, plan, anchor, self._loaded.packs).run()
        finally:
            store.close()

    def _meta(self, plan: SeedPlan, anchor: date) -> SnapshotMeta:
        """The metadata of the Snapshot of ``plan`` at ``anchor`` (requirement 20.10)."""
        versions = self.versions
        return SnapshotMeta(
            dataset=plan.dataset,
            version=plan.version,
            random_seed=plan.random_seed,
            anchor_date=anchor,
            closed_before=_closed_before(plan, anchor),
            current_user=plan.current_user,
            framework_version=versions.framework,
            meta_model_version=versions.meta_model,
            packs=versions.packs,
            dataset_sha256=self._digest(plan),
        )

    def _digest(self, plan: SeedPlan) -> str:
        """The SHA-256 of the bytes of the definition file of ``plan`` (req 20.12)."""
        path = self._instance_dir / plan.file
        try:
            data = path.read_bytes()
        except OSError as error:
            reason = _NO_DEFINITION_FILE.format(reason=error.strerror)
            raise SeedError(plan.file, None, reason) from error
        return hashlib.sha256(data).hexdigest()


